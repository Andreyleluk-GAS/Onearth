export const getLocalizedCategory = (cat: TransformerCategory, lang: Language): TransformerCategory => {
  const trans = CATEGORY_TRANSLATIONS[lang]?.[cat.slug];
  if (!trans) return cat;

  return {
    ...cat,
    title: trans.title,
    shortTitle: trans.shortTitle,
    compactTitle: trans.compactTitle || cat.compactTitle,
    description: trans.description,
    voltageHV: trans.voltageHV,
    voltageLV: trans.voltageLV,
    connectionGroup: trans.connectionGroup,
    regulationType: trans.regulationType,
    standardEquipment: trans.standardEquipment,
    options: trans.options,
  };
};

export const getLocalizedCategories = (lang: Language): TransformerCategory[] => {
  return TRANSFORMER_CATEGORIES.map((c) => getLocalizedCategory(c, lang));
};
